export const HOLIDAY_YEAR_MAX = 2026

/** 返回该日的法定节假日安排；无安排（含超出数据范围的年份）返回 null */
export function getHolidayPlan(dateKey: string): HolidayPlan | null {
  const hit = RAW[dateKey]
  if (!hit) return null
  return { name: hit[0], isOffDay: hit[1] === 1 }
}
